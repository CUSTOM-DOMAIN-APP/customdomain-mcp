#!/usr/bin/env node
// build-plugins.mjs: skills/ is the one source of skills. This script copies it into the two plugin folders
// that ship them (plugins/customdomain/skills for Claude, plugins/customdomain-openai/skills for Codex), so the
// copies cannot drift. Never edit a generated copy: change skills/ and run this script.
//
//   node scripts/build-plugins.mjs            validate, then regenerate both plugin skills folders
//   node scripts/build-plugins.mjs --check    validate, then fail if a generated folder differs (for CI)
//   node scripts/build-plugins.mjs --validate validate skills/ only
//
// Validation also checks every `METHOD /v1/path` call, webhook event name and `customdomain:` widget message the
// skills name against the product's API description and widget protocol file. This repo holds neither, so they are
// read from a local checkout of the main repo when CUSTOMDOMAIN_REPO_PATH is set, and otherwise fetched from the
// raw files at the commit pinned in scripts/validate-sources.json. When neither works, those checks are skipped
// with a warning and everything else still runs.
//
// Validation, per skill: the folder name is lowercase words joined by hyphens (up to 64 characters) and equals
// the frontmatter `name`; `description` is present and up to 1024 characters; frontmatter keys come only from the
// open Agent Skills format plus any key a target plugin needs; every markdown file is under 500 lines; relative
// links resolve inside the skill; no em or en dashes; nothing shaped like a key or secret. Needs Node 18 or newer
// and no packages.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "skills");

// Keys the open Agent Skills format defines.
const OPEN_KEYS = ["name", "description", "license", "compatibility", "metadata", "allowed-tools"];
const MAX_NAME = 64;
const MAX_DESCRIPTION = 1024;
const MAX_LINES = 500;

// Each target plugin: where its skills go, which skills it gets, and any extra frontmatter key it needs.
// The Codex plugin points at the connection and repair profile of the server, which has no domain search
// tools, so it leaves out find-a-domain.
const TARGETS = [
  { id: "claude", dir: "plugins/customdomain/skills", exclude: [], extraKeys: [] },
  { id: "openai", dir: "plugins/customdomain-openai/skills", exclude: ["find-a-domain"], extraKeys: [] },
];

const BANNER = (name) =>
  `<!-- Generated by scripts/build-plugins.mjs from skills/${name}. Edit the source in skills/, not this copy. -->\n`;

const SECRET_SHAPES = [
  /\b(?:cd|sk|rk)_(?:live|test)_[A-Za-z0-9]{8,}/,
  /\bsk_[0-9a-f]{32}\b/,
  /\bwhsec_[A-Za-z0-9]{8,}/,
  /\beyJ[A-Za-z0-9_-]{20,}/,
];

const args = new Set(process.argv.slice(2));
const mode = args.has("--check") ? "check" : args.has("--validate") ? "validate" : "build";

const errors = [];
const warnings = [];
const fail = (where, msg) => errors.push(`${where}: ${msg}`);

function listSkillNames() {
  return fs
    .readdirSync(SOURCE, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

function walk(dir, base = dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(full, base));
    else out.push(path.relative(base, full).split(path.sep).join("/"));
  }
  return out;
}

/** Splits a SKILL.md into its frontmatter fields and body. Values are plain text or one JSON string on one line. */
function parseFrontmatter(text, where) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) {
    fail(where, "no frontmatter block at the top");
    return null;
  }
  const fields = {};
  for (const line of m[1].split("\n")) {
    if (!line.trim()) continue;
    const kv = line.match(/^([A-Za-z][A-Za-z0-9-]*):\s*(.*)$/);
    if (!kv) {
      fail(where, `frontmatter line is not "key: value" on one line: ${line.slice(0, 60)}`);
      continue;
    }
    let value = kv[2].trim();
    if (value.startsWith('"')) {
      try {
        value = JSON.parse(value);
      } catch {
        fail(where, `frontmatter value for ${kv[1]} is not a valid quoted string`);
      }
    }
    fields[kv[1]] = value;
  }
  return { fields, end: m[0].length };
}

const EVENT_NAME = /^(connection|domain|certificate|credential|webhook)\.[a-z_]+$/;
// A call is `METHOD /v1/path`, `METHOD https://api.customdomain.ai/v1/path`, `-X METHOD <url>` or a bare API url
// (any method). A `<PLACEHOLDER>` in a path counts as one `{id}` segment.
const PATH_CHARS = "[A-Za-z0-9_\\-/{}<>:.]*[A-Za-z0-9_}>]";
const CALLS = [
  new RegExp(`\\b(GET|POST|PUT|PATCH|DELETE) (?:https://api\\.customdomain\\.ai)?(/v1/${PATH_CHARS})`, "g"),
  new RegExp(`-X (GET|POST|PUT|PATCH|DELETE) (?:"|')?https://api\\.customdomain\\.ai(/v1/${PATH_CHARS})`, "g"),
  new RegExp(`()https://api\\.customdomain\\.ai(/v1/${PATH_CHARS})`, "g"),
];
const template = (p) => p.replace(/^\/v1/, "").replace(/\{[^}]*\}|<[^>]*>/g, "{}");

/** Reads the OpenAPI file and the widget protocol file: local checkout first, then the pinned raw files. */
async function loadReference() {
  const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts/validate-sources.json"), "utf8"));
  const local = process.env.CUSTOMDOMAIN_REPO_PATH;
  const read = async (rel) => {
    if (local) return fs.readFileSync(path.join(local, rel), "utf8");
    const res = await fetch(`https://raw.githubusercontent.com/${cfg.repo}/${cfg.sha}/${rel}`, { signal: AbortSignal.timeout(15000) });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${rel}`);
    return res.text();
  };
  try {
    return { openapi: await read(cfg.files.openapi), protocol: await read(cfg.files.protocol) };
  } catch (e) {
    warnings.push(
      `skipped the API, event and widget message checks (${e.message}). Set CUSTOMDOMAIN_REPO_PATH to a local checkout of ${cfg.repo} to run them.`,
    );
    return null;
  }
}

/** Paths and their methods from the OpenAPI file, read line by line (plain block YAML). */
function loadApiPaths(text) {
  const paths = new Map();
  let inPaths = false;
  let cur = null;
  for (const line of text.split("\n")) {
    if (/^paths:/.test(line)) { inPaths = true; continue; }
    if (inPaths && /^[a-z]/.test(line)) break;
    if (!inPaths) continue;
    const p = /^ {2}(\/\S*):\s*$/.exec(line);
    if (p) { cur = new Set(); paths.set(p[1].replace(/^['"]|['"]$/g, ""), cur); continue; }
    const m = /^ {4}(get|post|put|patch|delete):/.exec(line);
    if (m && cur) cur.add(m[1].toUpperCase());
  }
  return paths;
}

/** Fails on any call, event or message a skill names that the reference files do not have. */
function checkAgainstReference(name, ref, apiPaths) {
  const known = new Map([...apiPaths].map(([p, methods]) => [template(p), methods]));
  const dir = path.join(SOURCE, name);
  for (const rel of walk(dir).filter((r) => r.endsWith(".md"))) {
    const at = `skills/${name}/${rel}`;
    const text = fs.readFileSync(path.join(dir, rel), "utf8");
    for (const re of CALLS) {
      for (const m of text.matchAll(re)) {
        const methods = known.get(template(m[2]));
        const label = `${m[1] ? m[1] + " " : ""}${m[2]}`;
        if (!methods) fail(at, `${label} is not in the API description`);
        else if (m[1] && !methods.has(m[1])) fail(at, `${label}: that method is not in the API description`);
      }
    }
    for (const m of text.matchAll(/`([a-z_]+\.[a-z_]+)`/g)) {
      if (EVENT_NAME.test(m[1]) && !ref.openapi.includes(m[1])) fail(at, `event ${m[1]} is not in the API description`);
    }
    for (const m of text.matchAll(/`(customdomain:[a-z-]+)`/g)) {
      if (!ref.protocol.includes(m[1])) fail(at, `widget message ${m[1]} is not in the protocol file`);
    }
  }
}

function validateSkill(name) {
  const dir = path.join(SOURCE, name);
  const skillFile = path.join(dir, "SKILL.md");
  const where = `skills/${name}`;
  if (!fs.existsSync(skillFile)) {
    fail(where, "SKILL.md is missing");
    return;
  }
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name) || name.length > MAX_NAME) {
    fail(where, `folder name must be lowercase words joined by single hyphens, up to ${MAX_NAME} characters`);
  }
  const fm = parseFrontmatter(fs.readFileSync(skillFile, "utf8"), `${where}/SKILL.md`);
  if (fm) {
    if (fm.fields.name !== name) fail(`${where}/SKILL.md`, `name "${fm.fields.name}" must equal the folder "${name}"`);
    const d = fm.fields.description;
    if (!d) fail(`${where}/SKILL.md`, "description is missing");
    else if (d.length > MAX_DESCRIPTION) fail(`${where}/SKILL.md`, `description is ${d.length} characters, the limit is ${MAX_DESCRIPTION}`);
    const allowed = new Set([...OPEN_KEYS, ...TARGETS.flatMap((t) => t.extraKeys)]);
    for (const key of Object.keys(fm.fields)) {
      if (!allowed.has(key)) fail(`${where}/SKILL.md`, `frontmatter key "${key}" is not in the open format or needed by a target`);
    }
  }
  for (const rel of walk(dir)) {
    if (!rel.endsWith(".md")) continue;
    const file = path.join(dir, rel);
    const at = `${where}/${rel}`;
    const text = fs.readFileSync(file, "utf8");
    const lines = text.split("\n").length;
    if (lines > MAX_LINES) fail(at, `${lines} lines, the limit is ${MAX_LINES}`);
    if (/[–—]/.test(text)) fail(at, "contains an em or en dash");
    for (const shape of SECRET_SHAPES) {
      if (shape.test(text)) fail(at, "contains something shaped like a key or secret");
    }
    // Relative links must resolve to a file inside this skill.
    const linkRe = /\]\(([^)\s]+)\)/g;
    let link;
    while ((link = linkRe.exec(text))) {
      const target = link[1];
      if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("#")) continue;
      const clean = target.split("#")[0];
      const resolved = path.resolve(path.dirname(file), clean);
      if (!resolved.startsWith(dir + path.sep) || !fs.existsSync(resolved)) fail(at, `relative link does not resolve inside the skill: ${target}`);
    }
  }
}

/** The files a target should hold: relative path to bytes. */
function render(target, names) {
  const files = new Map();
  for (const name of names) {
    if (target.exclude.includes(name)) continue;
    const dir = path.join(SOURCE, name);
    for (const rel of walk(dir)) {
      let bytes = fs.readFileSync(path.join(dir, rel));
      if (rel === "SKILL.md") {
        const text = bytes.toString("utf8");
        const end = text.match(/^---\n[\s\S]*?\n---\n/)[0].length;
        bytes = Buffer.from(text.slice(0, end) + "\n" + BANNER(name) + text.slice(end), "utf8");
      }
      files.set(`${name}/${rel}`, bytes);
    }
  }
  return files;
}

function check(target, expected) {
  const dir = path.join(ROOT, target.dir);
  const actual = fs.existsSync(dir) ? new Set(walk(dir)) : new Set();
  for (const [rel, bytes] of expected) {
    if (!actual.has(rel)) fail(target.dir, `missing ${rel}`);
    else if (!fs.readFileSync(path.join(dir, rel)).equals(bytes)) fail(target.dir, `${rel} differs from skills/`);
  }
  for (const rel of actual) if (!expected.has(rel)) fail(target.dir, `unexpected file ${rel}`);
}

function write(target, expected) {
  const dir = path.join(ROOT, target.dir);
  fs.rmSync(dir, { recursive: true, force: true });
  for (const [rel, bytes] of expected) {
    const file = path.join(dir, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
  }
}

const names = listSkillNames();
if (names.length === 0) fail("skills", "no skills found");
for (const name of names) validateSkill(name);
const reference = await loadReference();
if (reference) {
  const apiPaths = loadApiPaths(reference.openapi);
  if (apiPaths.size === 0) fail("skills", "the API description has no paths, so calls cannot be checked");
  for (const name of names) checkAgainstReference(name, reference, apiPaths);
}
for (const w of warnings) console.warn(`warning: ${w}`);

if (errors.length === 0 && mode !== "validate") {
  for (const target of TARGETS) {
    const expected = render(target, names);
    if (mode === "check") check(target, expected);
    else write(target, expected);
  }
}

if (errors.length) {
  console.error(errors.map((e) => `error: ${e}`).join("\n"));
  if (mode === "check") console.error("\nRun: node scripts/build-plugins.mjs");
  process.exit(1);
}
const verb = mode === "build" ? "built" : mode === "check" ? "up to date" : "valid";
console.log(`${names.length} skills ${verb}${mode === "validate" ? "" : " for " + TARGETS.map((t) => t.id).join(" and ")}.`);
